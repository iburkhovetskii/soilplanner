# Веса целевой функции (иерархия приоритетов)
WEIGHT_ROTATION_ERROR = 1000  # Штраф за 1 ошибку севооборота
WEIGHT_AREA_DEFICIT = 1       # Штраф за 1% недобора площади
WEIGHT_COMPACTNESS = 10       # Штраф за каждую отдельную культуру внутри подразделения
                              # (мягкое ограничение «кучности» — одинаковые культуры лучше сажать рядом)

# Балл факторов формирования СПП (app/core/factors, docs/FACTORS_SPP.md).
# В цель входит «сожаление»: regret[поле, культура] = лучший балл поля минус
# балл этой пары, 0..100. Вес подобран так, чтобы сохранить иерархию:
#   ошибка севооборота 1000 >> максимум балла на поле 300 > кучность 10 за пару
#   > ребро смежности 2 > 1% недобора площади 1.
# Один балл никогда не «покупает» нарушение севооборота: 3 × 100 < 1000.
WEIGHT_FACTOR_SCORE = 3
FACTOR_SCORE_MAX = 100        # Диапазон балла пары (0..100)
WEIGHT_FACTOR_SCORE_MAX = 50  # Потолок, который принимает API

# Взвешивание балла по площади поля: коэффициент домножается на
# min(площадь / FACTOR_AREA_REF_HA, FACTOR_AREA_CAP). Ограничитель обязателен:
# без него поле в 967 га (17 медиан) получило бы размах больше цены ошибки
# севооборота и охотно «купило» бы нарушение.
FACTOR_AREA_REF_HA = 57.0     # Медиана площади поля по актуальному снимку
FACTOR_AREA_CAP = 3.0

# Делать ли недопустимого предшественника (значение матрицы совместимости 0)
# жёстким запретом, как требует спецификация факторов. По умолчанию выключено:
# запрет снимает ~3% пар «поле × культура», а свободный люфт площадей всего
# ~10% (hard_ratio 0.9), поэтому включение может дать INFEASIBLE. Управляется
# флагом запроса hard_block_bad_predecessor.
