# Как трактовать значения матрицы совместимости.
#   'graded'   — значение матрицы (0.0/0.2/0.7/1.0) используется как K напрямую;
#   'discrete' — по спецификации: >= GOOD_THRESHOLD → K=1.0 («Good», +8 баллов),
#                иначе K=0.0 («Acceptable», без бонуса).
# По умолчанию 'graded': в матрице заказчика четыре градации, а спецификация
# знает только три (0/1/2), и градация 0.7 «Допустимый с оговорками» при
# дискретном режиме потеряла бы всю информацию.
PREDECESSOR_SCORING_MODE = "graded"
PREDECESSOR_GOOD_THRESHOLD = 0.9

# Значение матрицы, ниже или равно которому предшественник считается
# недопустимым (жёсткий фильтр по спецификации).
